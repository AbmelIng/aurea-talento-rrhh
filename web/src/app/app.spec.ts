import { TestBed } from '@angular/core/testing';
import { provideHttpClient } from '@angular/common/http';
import { provideHttpClientTesting } from '@angular/common/http/testing';
import { App } from './app';

describe('App', () => {
  beforeEach(async () => {
    sessionStorage.clear();
    await TestBed.configureTestingModule({
      imports: [App],
      providers: [provideHttpClient(), provideHttpClientTesting()],
    }).compileComponents();
  });

  it('should create the app', () => {
    const fixture = TestBed.createComponent(App);
    const app = fixture.componentInstance;
    expect(app).toBeTruthy();
  });

  it('shows the local demo login and fills a role account', async () => {
    const fixture = TestBed.createComponent(App);
    await fixture.whenStable();
    const compiled = fixture.nativeElement as HTMLElement;
    expect(compiled.querySelector('h1')?.textContent).toContain('La firma empieza');
    const demo = Array.from(compiled.querySelectorAll<HTMLButtonElement>('.demo-account')).find(button => button.textContent?.includes('Gerente'));
    demo?.click();
    expect(fixture.componentInstance.loginForm.getRawValue()).toEqual({ email: 'carlos@demo.local', password: 'Demo2026!' });
  });
});
