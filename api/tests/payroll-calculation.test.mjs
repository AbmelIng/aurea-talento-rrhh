import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseService } from '../dist/database.js';
import { PayrollCalculationService } from '../dist/payroll-calculation.service.js';

test('condiciones vigentes, horas y ausencias aprobadas, borradores, aprobación separada e historial', async()=>{
  const folder=mkdtempSync(join(tmpdir(),'aurea-paycalc-'));
  process.env.SQLITE_FILE=join(folder,'paycalc.sqlite');
  const db=new DatabaseService();
  try {
    await db.initialize();
    const insertEmployee=async(code,status='Activo')=>db.run(`INSERT INTO employees (code,first_name,last_name,work_email,hire_date,job_title,area,office,employment_type,status) VALUES (?,?,?,?,?,?,?,?,?,?)`,[code,code,'Prueba',`${code.toLowerCase()}@example.test`,'2026-10-01','Auditor','Auditoría','Guatemala','Indefinido',status]);
    const payEmployee=await insertEmployee('PAGO','Inactivo');
    const adminEmployee=await insertEmployee('ADMIN','Inactivo');
    const salaried=await insertEmployee('MENSUAL');
    const hourly=await insertEmployee('HORA');
    const professional=await insertEmployee('HONORARIOS');
    const payrollUserId=await db.run('INSERT INTO users (employee_id,email,password_hash,role) VALUES (?,?,?,?)',[payEmployee,'pago@example.test','x','PAYROLL']);
    const adminUserId=await db.run('INSERT INTO users (employee_id,email,password_hash,role) VALUES (?,?,?,?)',[adminEmployee,'admin@example.test','x','ADMIN']);
    const payroll={id:payrollUserId,employee_id:payEmployee,role:'PAYROLL'};
    const admin={id:adminUserId,employee_id:adminEmployee,role:'ADMIN'};
    const service=new PayrollCalculationService(db);
    const period=await db.run('INSERT INTO payroll_periods (label,start_date,end_date,submit_deadline,pay_date,status,created_by,updated_at) VALUES (?,?,?,?,?,?,?,?)',['Primera quincena','2026-11-01','2026-11-15','2026-11-15','2026-11-20','Abierto',payrollUserId,new Date().toISOString()]);
    await service.addCondition(payroll,{employee_id:salaried,kind:'SALARIO_MENSUAL',amount:3000,effective_from:'2026-01-01',daily_hours:8});
    await service.addCondition(payroll,{employee_id:hourly,kind:'TARIFA_HORA',amount:100,effective_from:'2026-01-01'});
    await service.addCondition(payroll,{employee_id:professional,kind:'SERVICIOS_PROFESIONALES',amount:200,effective_from:'2026-01-01'});
    const concurrent=await Promise.allSettled([100,110].map(rate=>service.addCondition(payroll,{employee_id:payEmployee,kind:'TARIFA_HORA',amount:rate,effective_from:'2026-01-01'})));
    assert.equal(concurrent.filter(result=>result.status==='fulfilled').length,1,'Dos altas simultáneas no crean vigencias superpuestas');
    await assert.rejects(()=>service.addCondition(payroll,{employee_id:hourly,kind:'TARIFA_HORA',amount:110,effective_from:'2026-11-01'}),/solapa/);
    const sheet=async(employeeId,entries)=>{
      const id=await db.run('INSERT INTO timesheets (period_id,employee_id,status) VALUES (?,?,?)',[period,employeeId,'Aprobada']);
      for(const [day,hours] of entries) await db.run('INSERT INTO time_entries (timesheet_id,work_date,hours,updated_at) VALUES (?,?,?,?)',[id,day,hours,new Date().toISOString()]);
    };
    await sheet(hourly,[['2026-11-02',8],['2026-11-03',4]]);
    await sheet(professional,[['2026-11-02',10]]);
    const unpaidType=await db.run('INSERT INTO leave_types (name,pay_treatment) VALUES (?,?)',['Permiso no pagado','No pagada']);
    const paidType=await db.run('INSERT INTO leave_types (name,pay_treatment) VALUES (?,?)',['Vacación pagada','Pagada']);
    await db.run('INSERT INTO leave_requests (employee_id,leave_type_id,start_date,end_date,hours,status,created_at) VALUES (?,?,?,?,?,?,?)',[salaried,unpaidType,'2026-11-04','2026-11-04',8,'Aprobada',new Date().toISOString()]);
    await db.run('INSERT INTO leave_requests (employee_id,leave_type_id,start_date,end_date,hours,status,created_at) VALUES (?,?,?,?,?,?,?)',[hourly,paidType,'2026-11-04','2026-11-04',8,'Aprobada',new Date().toISOString()]);
    await service.addAdjustment(payroll,{period_id:period,employee_id:salaried,kind:'BONO',amount:200,reason:'Bono aprobado'});
    await service.addAdjustment(payroll,{period_id:period,employee_id:salaried,kind:'IMPUESTO',amount:50,reason:'Impuesto calculado externamente'});
    const run=await service.generate(payroll,period);
    assert.equal(run.items.length,3);
    const item=(employeeId)=>run.items.find(i=>Number(i.employee_id)===employeeId);
    assert.equal(Number(item(salaried).base_amount),1400);
    assert.equal(Number(item(salaried).net),1550);
    assert.equal(Number(item(hourly).net),2000);
    assert.equal(Number(item(professional).net),2000);
    assert.equal(item(professional).detail.professional_services,true);
    await service.submit(payroll,period);
    await assert.rejects(()=>service.publish(payroll,period),/aprobación/);
    await assert.rejects(()=>service.approve(payroll,period,true),/administración/);
    await service.approve(admin,period,true);
    await service.publish(payroll,period);
    assert.equal((await service.run(admin,period)).status,'Publicado');
    assert.equal((await service.history(admin)).length,1);
    assert.equal((await service.history(admin))[0].people_count,3);
    assert.equal(Number((await service.history(admin))[0].professional_fees),2000);
    assert.equal((await db.all('SELECT id FROM pay_records WHERE period_id=?',[period])).length,2,'Los honorarios no generan boleta salarial');
    assert.equal(Number((await db.get('SELECT net FROM pay_records WHERE period_id=? AND employee_id=?',[period,salaried])).net),1550);
    assert.equal((await db.all('SELECT id FROM pay_conditions WHERE employee_id=?',[salaried])).length,1,'La condición histórica se conserva');
    const oldHourly=(await service.conditions(payroll,hourly))[0];
    await service.closeCondition(payroll,Number(oldHourly.id),'2026-11-15');
    await service.addCondition(payroll,{employee_id:hourly,kind:'TARIFA_HORA',amount:125,effective_from:'2026-11-16'});
    assert.equal((await service.conditions(payroll,hourly)).length,2,'El cambio de tarifa conserva la condición anterior');
    const nextPeriod=await db.run('INSERT INTO payroll_periods (label,start_date,end_date,submit_deadline,pay_date,status,created_by,updated_at) VALUES (?,?,?,?,?,?,?,?)',['Segunda quincena','2026-11-16','2026-11-30','2026-11-30','2026-12-05','Abierto',payrollUserId,new Date().toISOString()]);
    const nextHourlySheet=await db.run('INSERT INTO timesheets (period_id,employee_id,status) VALUES (?,?,?)',[nextPeriod,hourly,'Aprobada']);
    const nextProfessionalSheet=await db.run('INSERT INTO timesheets (period_id,employee_id,status) VALUES (?,?,?)',[nextPeriod,professional,'Aprobada']);
    await db.run('INSERT INTO time_entries (timesheet_id,work_date,hours,updated_at) VALUES (?,?,?,?)',[nextHourlySheet,'2026-11-17',8,new Date().toISOString()]);
    await db.run('INSERT INTO time_entries (timesheet_id,work_date,hours,updated_at) VALUES (?,?,?,?)',[nextProfessionalSheet,'2026-11-17',2,new Date().toISOString()]);
    const nextRun=await service.generate(payroll,nextPeriod);
    assert.equal(Number(nextRun.items.find(i=>Number(i.employee_id)===hourly).base_amount),1000,'El nuevo período usa la tarifa vigente de Q125');
    assert.equal(Number(nextRun.items.find(i=>Number(i.employee_id)===salaried).base_amount),1500,'La segunda quincena toma el resto del salario mensual');
    await assert.rejects(()=>service.generate(payroll,period),/Período cerrado/);
  } finally { await db.onModuleDestroy(); rmSync(folder,{recursive:true,force:true}); }
});
